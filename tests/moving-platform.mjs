import assert from 'node:assert/strict';
import * as THREE from '../dist/lib/three.module.js';
import {World} from '../dist/world.js';
import {makeMovingPlatform} from '../dist/moving-platform.js';
import {disposeBranch} from '../dist/streaming.js';
import {attachClay} from './load-clay.mjs';
const w=Object.create(World.prototype);w.mat={};await attachClay(w);
const roots=[new THREE.Group(),new THREE.Group()];roots[1].position.set(100,12,0);
const views=roots.map(root=>makeMovingPlatform(w,{w:4,y:0},root));
const grain=root=>root.children.filter(o=>o.name==='Inset flowing wood grain').map(o=>o.geometry);
const first=grain(roots[0]),second=grain(roots[1]);
assert(first.length>0);assert(first.every((g,i)=>g===second[i]),'matching streamed lifts reuse the carved surface at different world positions');
let disposed=0;first.forEach(g=>g.addEventListener('dispose',()=>disposed++));
disposeBranch(w,roots[0]);assert.equal(disposed,0,'streaming out one lift preserves the other lift’s wood detail');
assert(second.every(g=>w.assetGeometry.has(g)));
const timber=roots[1].getObjectByName('Rounded orange timber beam').geometry;
disposeBranch(w,roots[1]);timber.dispose();
assert.equal(disposed,first.length,'timber eviction also frees the shared wood detail');
assert(first.every(g=>!w.assetGeometry.has(g)));assert(!w.movingPlatformGrain.has(timber));
console.log('PASS moving-platform grain reuse, independent streamed views and shared geometry eviction');
